#!/usr/bin/env python3
"""Write paper/fig_strip.tex: per-seed divergence rate of every arm, as a dot strip plot.

Reads only the committed analysis files, so the figure recomputes from the data:

    .venv/bin/python scripts/make_strip_figure.py
"""

from __future__ import annotations

import json
import statistics
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
WIDTH = 5.8  # cm of plot width for 0..100 %
ROW = 0.42  # cm between rows

# (label, analysis file, run key); Kotlin none/probe are the pooled ten seeds
ROWS = [
    ("Dart", None, None),
    ("none", "analysis-extension.json", "dart/none"),
    ("human", "analysis-extension.json", "dart/human"),
    ("code", "analysis-extension.json", "dart/code"),
    ("probe", "analysis-extension.json", "dart/probe"),
    ("sysprobe", "analysis-extension.json", "dart/sysprobe"),
    ("probe-gpt41", "analysis-extension.json", "dart/probe-gpt41"),
    ("Kotlin", None, None),
    ("none", "analysis-kotlin-pooled.json", "kotlin/none"),
    ("probe", "analysis-kotlin-pooled.json", "kotlin/probe"),
    ("sysprobe", "analysis-extension.json", "kotlin/sysprobe"),
]


def rates(file: str, key: str) -> list[float]:
    runs = json.loads((ROOT / "artifacts" / file).read_text())["runs"][key]
    return [run["rate_total"] for run in runs]


def main() -> None:
    x = lambda value: value / 100 * WIDTH  # noqa: E731
    out = [
        "% Generated by scripts/make_strip_figure.py from artifacts/analysis*.json; do not edit.",
        "\\begin{tikzpicture}[font=\\footnotesize]",
    ]
    y = 0.0
    bottom = 0.0
    for label, file, key in ROWS:
        if file is None:
            out.append(f"\\node[anchor=west, font=\\footnotesize\\bfseries] at (-2.0,{y:.2f}) {{{label}}};")
            y -= ROW
            continue
        values = rates(file, key)
        mean = statistics.mean(values)
        out.append(f"\\node[anchor=east] at (-0.1,{y:.2f}) {{{label}}};")
        out.append(f"\\draw[black!12] (0,{y:.2f}) -- ({WIDTH},{y:.2f});")
        for value in values:
            out.append(f"\\fill[black!70] ({x(value):.3f},{y:.2f}) circle (1.5pt);")
        out.append(f"\\draw[black, line width=1.1pt] ({x(mean):.3f},{y - 0.15:.2f}) -- ({x(mean):.3f},{y + 0.15:.2f});")
        out.append(f"\\node[anchor=west, black!70] at ({WIDTH + 0.08},{y:.2f}) {{{mean:.1f}}};")
        bottom = y
        y -= ROW
    axis = bottom - 0.32
    out.append(f"\\draw[black!60] (0,{axis:.2f}) -- ({WIDTH},{axis:.2f});")
    for tick in range(0, 101, 20):
        out.append(f"\\draw[black!60] ({x(tick):.3f},{axis:.2f}) -- ({x(tick):.3f},{axis - 0.07:.2f});")
        out.append(f"\\node[anchor=north, black!70] at ({x(tick):.3f},{axis - 0.07:.2f}) {{{tick}}};")
    out.append(
        f"\\node[anchor=north] at ({WIDTH / 2:.2f},{axis - 0.38:.2f}) "
        "{divergent documents (\\% of all generated)};"
    )
    out.append(f"\\node[anchor=south west, black!70] at ({WIDTH + 0.02},0.12) {{mean}};")
    out.append("\\end{tikzpicture}")
    (ROOT / "paper" / "fig_strip.tex").write_text("\n".join(out) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
