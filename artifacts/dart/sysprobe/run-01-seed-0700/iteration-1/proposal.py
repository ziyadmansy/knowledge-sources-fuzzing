        i = draw(st.integers(min_value=-2**40, max_value=2**40))
        # Decide representation mode: int, float, exponent
        mode = draw(st.sampled_from(["int", "float", "exponent"]))
        if mode == "int":
            return str(i)
        elif mode == "float":
            # Represent as float by adding ".0" or ".5"
            # Use i as base integer part, add fractional part
            frac = draw(st.sampled_from([".0", ".5"]))
            return str(i) + frac
        else:
            # exponent form: e.g. 1e3, -2e-2
            exp = draw(st.integers(min_value=-10, max_value=10))
